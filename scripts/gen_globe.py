#!/usr/bin/env python3
"""Bake a 1-bit equirectangular land mask from Natural Earth 1:50m.

Each cell is land when land covers at least half of it, measured on a
4x finer raster, so coasts land where the vectors put them."""

import json
from pathlib import Path
from urllib.request import urlopen

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
NE = Path("/tmp/ne50")
NE_BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson"
W, H = 400, 200
SS = 4  # supersampling per cell side


def source_path(name):
    path = NE / name
    if not path.exists():
        NE.mkdir(parents=True, exist_ok=True)
        with urlopen(f"{NE_BASE}/{name}") as response:
            path.write_bytes(response.read())
    return path


def load(name):
    return json.loads(source_path(name).read_text())["features"]


def rings(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        yield c
    elif t == "MultiPolygon":
        yield from c


def raster(features, fill=1, base=None):
    im = base or Image.new("L", (W * SS, H * SS), 0)
    draw = ImageDraw.Draw(im)
    for feat in features:
        for poly in rings(feat["geometry"]):
            ext = [((lon + 180) / 360 * W * SS, (90 - lat) / 180 * H * SS) for lon, lat in poly[0]]
            if len(ext) >= 3:
                draw.polygon(ext, fill=fill)
            for hole in poly[1:]:
                pts = [((lon + 180) / 360 * W * SS, (90 - lat) / 180 * H * SS) for lon, lat in hole]
                if len(pts) >= 3:
                    draw.polygon(pts, fill=0)
    return im


def cells(fine):
    """Land where at least half of a cell's SS x SS subpixels are land."""
    pix = fine.load()
    im = Image.new("L", (W, H), 0)
    out = im.load()
    for y in range(H):
        for x in range(W):
            n = sum(pix[x * SS + i, y * SS + j] for j in range(SS) for i in range(SS))
            out[x, y] = 1 if 2 * n >= SS * SS else 0
    return im


def pack(im):
    pix = im.load()
    buf = bytearray((W * H + 7) // 8)
    for y in range(H):
        for x in range(W):
            if pix[x, y]:
                i = y * W + x
                buf[i >> 3] |= 1 << (i & 7)
    return buf


def c_source(packed):
    """src/c/worldmask.c for a packed mask (kept in flash, never decoded)."""
    rows = []
    for i in range(0, len(packed), 16):
        rows.append("\t" + ", ".join(f"0x{b:02x}" for b in packed[i:i + 16]) + ",")
    body = "\n".join(rows)
    return f"""// 1-bit equirectangular land mask {W}x{H}. Made with Natural Earth 1:50m (public domain).
// Generated by scripts/gen_globe.py. Land is bit i & 7 of byte i >> 3, for i = y * MASK_W + x.
#include "tables.h"

const uint8_t WORLD_MASK[MASK_W * MASK_H / 8] = {{
{body}
}};
"""


def main():
    fine = raster(load("ne_50m_land.geojson"))
    raster(load("ne_50m_lakes.geojson"), fill=0, base=fine)
    land = cells(fine)
    packed = pack(land)
    out = ROOT / "src" / "c" / "worldmask.c"
    out.write_text(c_source(packed))
    print("wrote", out, out.stat().st_size, "bytes", "land", sum(1 for p in land.getdata() if p))


if __name__ == "__main__":
    main()
