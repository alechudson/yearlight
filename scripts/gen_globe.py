#!/usr/bin/env python3
"""Bake a 1-bit equirectangular land mask from Natural Earth 110m."""

import json
from pathlib import Path
from urllib.request import urlopen

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
NE = Path("/tmp/ne110")
NE_BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson"
W, H = 200, 100


def source_path(name):
    path = NE / name
    if not path.exists():
        NE.mkdir(parents=True, exist_ok=True)
        with urlopen(f"{NE_BASE}/{name}") as response:
            path.write_bytes(response.read())
    return path


def load(name):
    return json.loads(source_path(name).read_text())["features"]


def rings(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "Polygon":
        yield c
    elif t == "MultiPolygon":
        yield from c


def raster(features, fill=1, base=None):
    im = base or Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(im)
    for feat in features:
        for poly in rings(feat["geometry"]):
            ext = [((lon + 180) / 360 * W, (90 - lat) / 180 * H) for lon, lat in poly[0]]
            if len(ext) >= 3:
                draw.polygon(ext, fill=fill)
            for hole in poly[1:]:
                pts = [((lon + 180) / 360 * W, (90 - lat) / 180 * H) for lon, lat in hole]
                if len(pts) >= 3:
                    draw.polygon(pts, fill=0)
    return im


def pack(im):
    pix = im.load()
    buf = bytearray((W * H + 7) // 8)
    for y in range(H):
        for x in range(W):
            if pix[x, y]:
                i = y * W + x
                buf[i >> 3] |= 1 << (i & 7)
    return buf


def nibble(code):
    return code - 48 if code < 58 else code - 87


ROWS_PER_PART = 4


def module_source(packed):
    """worldmask.js for a packed mask: hex, ROWS_PER_PART mask rows per string.

    XS on the watch has no string index cache, so charCodeAt(i) walks the
    string from its start. One 5000-character string made every lookup (and
    the old decode-at-load loop) O(n); four-row strings keep each lookup
    under 200 steps and leave nothing to decode into RAM.
    """
    assert W % 8 == 0 and ROWS_PER_PART == 4 and H % ROWS_PER_PART == 0
    hexstr = bytes(packed).hex()
    row = W // 4
    part = row * ROWS_PER_PART
    parts = "\n".join(f'\t"{hexstr[i:i + part]}",' for i in range(0, len(hexstr), part))
    return f"""// 1-bit equirectangular land mask {W}x{H}. Made with Natural Earth 1:110m (public domain).
// Generated by scripts/gen_globe.py. Hex bytes, bit i & 7 of byte i >> 3 for i = y * MASK_W + x,
// {ROWS_PER_PART} mask rows per string: XS indexes a string by walking it from the start, so short
// strings keep each lookup cheap, and nothing is decoded into RAM at launch.
export const MASK_W = {W};
export const MASK_H = {H};
const ROW_CHARS = {row};
const PARTS = [
{parts}
];

// Land bit for mask cell x (0..MASK_W-1), y (0..MASK_H-1).
export function isLandCell(x, y) {{
	const c = PARTS[y >> 2].charCodeAt((y & 3) * ROW_CHARS + ((x >> 3) << 1) + ((x & 7) < 4 ? 1 : 0));
	return ((c < 58 ? c - 48 : c - 87) >> (x & 3)) & 1;
}}
"""


def main():
    land = raster(load("ne_110m_land.geojson"))
    raster(load("ne_110m_lakes.geojson"), fill=0, base=land)
    packed = pack(land)
    out = ROOT / "src" / "embeddedjs" / "worldmask.js"
    out.write_text(module_source(packed))
    print("wrote", out, out.stat().st_size, "bytes", "land", sum(1 for p in land.getdata() if p))


if __name__ == "__main__":
    main()
